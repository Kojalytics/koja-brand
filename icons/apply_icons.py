#!/usr/bin/env python3
"""Puts the Kojalytics icon of one app into its repository, in every format and size it already uses.

    apply_icons.py <repo> <app-id>        an app: assets/app-icon/** (svg, png at their own size,
                                          icns from the macOS variant, ico) and attribution sidecars
    apply_icons.py <launcher> --launcher  the launcher's per-app tiles: assets/app-icons/<id>.png

Existing files are replaced in place (same name, same pixel size), so code that embeds them keeps
working. Needs resvg, Pillow and (for .icns) macOS iconutil. Run make_icons.py first.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SKIP = ("document", "license", "readme", "icon-source", ".attribution", ".md", ".txt")


def render(svg: Path, px: int) -> Image.Image:
    with tempfile.TemporaryDirectory() as t:
        out = Path(t) / "i.png"
        subprocess.run(["resvg", "-w", str(px), "-h", str(px), str(svg), str(out)], check=True)
        return Image.open(out).convert("RGBA").copy()


def write_png(svg: Path, dst: Path) -> None:
    w, h = Image.open(dst).size
    big = render(svg, max(w, h) * 2).resize((w, h), Image.LANCZOS)   # 2x then down: crisper edges
    big.save(dst, optimize=True)


def write_ico(svg: Path, dst: Path) -> None:
    sizes = [16, 24, 32, 48, 64, 128, 256]
    render(svg, 512).resize((256, 256), Image.LANCZOS).save(dst, sizes=[(s, s) for s in sizes])


def write_icns(svg: Path, dst: Path) -> None:
    with tempfile.TemporaryDirectory() as t:
        iconset = Path(t) / "icon.iconset"
        iconset.mkdir()
        full = render(svg, 1024)
        for s in (16, 32, 128, 256, 512):
            full.resize((s, s), Image.LANCZOS).save(iconset / f"icon_{s}x{s}.png")
            full.resize((s * 2, s * 2), Image.LANCZOS).save(iconset / f"icon_{s}x{s}@2x.png")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(dst)], check=True)


ATTRIBUTION = """asset:        {asset}
title:        {name} app icon
author:       Kojalytics
source:       original work, generated by brand/icons/make_icons.py (github.com/Kojalytics/koja-brand)
license:      Kojalytics trademark, not covered by the code licence (see NOTICE)
added:        by Kojalytics
notes:        replaces the original app icon; the Kojalytics name and logos are trademarks of Kojalytics.
"""


def apply_app(repo: Path, app_id: str) -> int:
    import make_icons
    flat, mac = HERE / f"{app_id}.svg", HERE / f"{app_id}-macos.svg"
    name = make_icons.APPS[app_id][0]
    root = repo / "assets" / "app-icon"
    if not root.is_dir():
        sys.exit(f"{root} not found")
    n = 0
    for f in sorted(p for p in root.rglob("*") if p.is_file()):
        low = f.name.lower()
        if any(k in low for k in SKIP):
            continue
        if f.suffix == ".svg":
            shutil.copyfile(flat, f)
        elif f.suffix == ".png":
            write_png(mac if "macos" in low else flat, f)
        elif f.suffix == ".icns":
            write_icns(mac, f)
        elif f.suffix == ".ico":
            write_ico(flat, f)
        else:
            continue
        n += 1
        side = f.with_name(f.name + ".attribution")
        if side.exists():
            side.write_text(ATTRIBUTION.format(asset=f.name, name=name))
    return n


def apply_launcher(repo: Path) -> int:
    import make_icons
    n = 0
    for app_id in make_icons.ICONS:
        dst = repo / "assets" / "app-icons" / f"{app_id}.png"
        if dst.exists():
            write_png(HERE / f"{app_id}.svg", dst)
            n += 1
    return n


if __name__ == "__main__":
    sys.path.insert(0, str(HERE))
    repo = Path(sys.argv[1]).resolve()
    if sys.argv[2] == "--launcher":
        print(f"launcher: {apply_launcher(repo)} app tiles")
    else:
        print(f"{sys.argv[2]}: {apply_app(repo, sys.argv[2])} icon files")
